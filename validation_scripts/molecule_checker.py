if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser(description="SynAgent MoleculeChecker")
    parser.add_argument(
        "--tar",
        default=r"top_poses.tar-3\top_poses.tar-3",
        help="Path to the top_poses tar file",
    )
    parser.add_argument(
        "--sulfonamide-limit", type=int, default=3,
        help="Kill molecules with >= N sulfonamide groups (default: 3)",
    )
    parser.add_argument(
        "--sa-limit", type=float, default=6.0,
        help="Kill molecules with SA score > N (default: 6.0)",
    )
    parser.add_argument(
        "--show-passed", action="store_true",
        help="Print SMILES and properties for molecules that pass all checks",
    )
    args = parser.parse_args()

    checker = MoleculeChecker(
        sulfonamide_limit=args.sulfonamide_limit,
        sa_score_limit=args.sa_limit,
    )

    print(f"Loading molecules from: {args.tar}")
    results = checker.check_from_tar(args.tar)

    checker.print_summary(results)

    if args.show_passed:
        print("Molecules that passed all checks:")
        print("-" * 55)
        for r in results:
            if r.passed:
                props = r.properties
                print(f"  SMILES      : {r.smiles}")
                print(f"  MW          : {props.get('MW', '?'):.1f}")
                print(f"  LogP        : {props.get('LogP', '?'):.2f}")
                print(f"  Charge      : {props.get('formal_charge', '?')}")
                print(f"  Sulfonamides: {props.get('sulfonamide_count', '?')}")
                print(f"  SA Score    : {props.get('sa_score', '?')}")
                print(f"  Warnings    : {'; '.join(r.warnings) or 'none'}")
                if r.protein:
                    print(f"  Protein     : {r.protein}  "
                          f"GID4 dock = {r.gid4_dock}  "
                          f"iMiner = {r.iminer}")
                print()
